export const CANVAS_W = 760;
export const CANVAS_H = 480;
export const GRID_SIZE_METERS = 200;
export const INIT_ENERGY_J = 0.5;

const PAD_X = 48;
const PAD_Y = 38;
const PLOT_W = CANVAS_W - PAD_X * 2;
const PLOT_H = CANVAS_H - PAD_Y * 2;

export function metersToCanvas(xm, ym) {
  return {
    cx: PAD_X + (xm / GRID_SIZE_METERS) * PLOT_W,
    cy: PAD_Y + (1 - ym / GRID_SIZE_METERS) * PLOT_H,
  };
}

export function canvasToMeters(cx, cy) {
  const clampedX = Math.max(PAD_X, Math.min(CANVAS_W - PAD_X, cx));
  const clampedY = Math.max(PAD_Y, Math.min(CANVAS_H - PAD_Y, cy));
  return {
    xm: Number((((clampedX - PAD_X) / PLOT_W) * GRID_SIZE_METERS).toFixed(2)),
    ym: Number(((1 - (clampedY - PAD_Y) / PLOT_H) * GRID_SIZE_METERS).toFixed(2)),
  };
}

