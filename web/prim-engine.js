export function createRandomConnectedGraph(nodeCount = 9) {
  const nodes = [];
  const margin = 24;
  for (let i = 0; i < nodeCount; i += 1) {
    let xm = 100;
    let ym = 100;
    for (let attempt = 0; attempt < 40; attempt += 1) {
      xm = Number((margin + Math.random() * (GRID_SIZE_METERS - margin * 2)).toFixed(1));
      ym = Number((margin + Math.random() * (GRID_SIZE_METERS - margin * 2)).toFixed(1));
      const tooClose = nodes.some((other) => Math.hypot(other.xm - xm, other.ym - ym) < 34);
      if (!tooClose) break;
    }
    const e = Number((0.18 + Math.random() * 0.37).toFixed(2));
    nodes.push({
      id: i,
      label: i === 0 ? "S0" : `N${i}`,
      xm,
      ym,
      e,
      ...metersToCanvas(xm, ym),
    });
  }

  const edges = [];
  for (let i = 0; i < nodes.length; i += 1) {
    for (let j = i + 1; j < nodes.length; j += 1) {
      const d = euclideanMeters(nodes[i], nodes[j]);
      if (d <= 82) {
        edges.push({
          id: `${i}-${j}`,
          u: i,
          v: j,
          manualWeight: Number(d.toFixed(1)),
        });
      }
    }
  }
  connectComponents(nodes, edges);

  return {
    presetKey: "custom",
    isDynamicDistance: true,
    defaultRoot: 0,
    nodes,
    edges,
  };
}

export function getEdgeBaseWeight(edge, nodeMap, isDynamicDistance) {
  if (!isDynamicDistance && typeof edge.manualWeight === "number") {
    return edge.manualWeight;
  }
  const uNode = nodeMap.get(edge.u);
  const vNode = nodeMap.get(edge.v);
  if (!uNode || !vNode) return 0;
  return Number(euclideanMeters(uNode, vNode).toFixed(1));
}

export function computeCompositeWeight(edge, fromId, toId, nodeMap, degreeMap, isDynamicDistance, maxBaseWeight) {
  const base = getEdgeBaseWeight(edge, nodeMap, isDynamicDistance);
  const fromNode = nodeMap.get(fromId);
  const toNode = nodeMap.get(toId);
  const normDist = maxBaseWeight > 0 ? base / maxBaseWeight : 0;
  const minEnergy = Math.min(fromNode?.e ?? INIT_ENERGY_J, toNode?.e ?? INIT_ENERGY_J);
  const energyFactor = Math.max(0, 1 - minEnergy / (INIT_ENERGY_J * 1.1));
  const loadFactor = (degreeMap.get(fromId) ?? 0) / Math.max(1, nodeMap.size);
  return 0.5 * normDist + 0.35 * energyFactor + 0.15 * loadFactor;
}

export function formatWeight(val, weightMode) {
  if (weightMode === "energy") {
    return val.toFixed(3);
  }
  return Number.isInteger(val) ? String(val) : val.toFixed(1);
}

export function buildPrimTrace(graph, startId, weightMode) {
  const { nodes, edges, isDynamicDistance } = graph;
  const nodeMap = new Map(nodes.map((n) => [n.id, n]));
  if (!nodeMap.has(startId) && nodes.length > 0) {
    startId = nodes[0].id;
  }

  let maxBaseWeight = 1;
  for (const edge of edges) {
    const w = getEdgeBaseWeight(edge, nodeMap, isDynamicDistance);
    if (w > maxBaseWeight) maxBaseWeight = w;
  }

  const adj = new Map(nodes.map((n) => [n.id, []]));
  for (const edge of edges) {
    if (adj.has(edge.u) && adj.has(edge.v)) {
      adj.get(edge.u).push({ neighbor: edge.v, edge });
      adj.get(edge.v).push({ neighbor: edge.u, edge });
    }
  }

  const labelOf = (id) => nodeMap.get(id)?.label ?? String(id);
  const takenNodes = new Set();
  const takenEdges = [];
  const degreeMap = new Map(nodes.map((n) => [n.id, 0]));
  const pq = [];
  const frames = [];
  let totalWeight = 0;

  const snapshot = (overrides = {}) => ({
    takenNodes: new Set(takenNodes),
    takenEdges: takenEdges.map((e) => ({ ...e })),
    pq: [...pq].sort((a, b) => a.weight - b.weight || a.from - b.from || a.to - b.to),
    activeNode: null,
    candidateEdge: null,
    rejectedEdge: null,
    totalWeight,
    line: 0,
    narration: "",
    ...overrides,
  });

  if (nodes.length === 0) {
    frames.push(
      snapshot({
        line: 0,
        narration: "Graf belum punya simpul. Pilih Tambah node lalu klik di kanvas.",
      })
    );
    return frames;
  }

  takenNodes.add(startId);
  frames.push(
    snapshot({
      activeNode: startId,
      line: 0,
      narration: `Mulai pohon T dari simpul awal ${labelOf(startId)}.`,
    })
  );

  // Push incident edges of root
  const rootNeighbors = adj.get(startId) || [];
  for (const item of rootNeighbors) {
    const weight =
      weightMode === "energy"
        ? computeCompositeWeight(item.edge, startId, item.neighbor, nodeMap, degreeMap, isDynamicDistance, maxBaseWeight)
        : getEdgeBaseWeight(item.edge, nodeMap, isDynamicDistance);
    pq.push({
      edgeId: item.edge.id,
      from: startId,
      to: item.neighbor,
      weight,
    });
  }

  if (rootNeighbors.length > 0) {
    frames.push(
      snapshot({
        activeNode: startId,
        line: 1,
        narration: `Masukkan ${rootNeighbors.length} sisi dari ${labelOf(startId)} ke antrean prioritas (PQ).`,
      })
    );
  }

  while (pq.length > 0 && takenNodes.size < nodes.length) {
    pq.sort((a, b) => a.weight - b.weight || a.from - b.from || a.to - b.to);
    const top = pq.shift();

    frames.push(
      snapshot({
        activeNode: top.from,
        candidateEdge: top,
        line: 3,
        narration: `Ambil sisi terkecil (${labelOf(top.from)}, ${labelOf(top.to)}) dengan bobot ${formatWeight(top.weight, weightMode)} dari PQ.`,
      })
    );

    if (takenNodes.has(top.to)) {
      frames.push(
        snapshot({
          activeNode: top.from,
          rejectedEdge: top,
          line: 4,
          narration: `Lewati (${labelOf(top.from)}, ${labelOf(top.to)}): simpul ${labelOf(top.to)} sudah ada di T.`,
        })
      );
      continue;
    }

    takenNodes.add(top.to);
    takenEdges.push(top);
    degreeMap.set(top.from, (degreeMap.get(top.from) ?? 0) + 1);
    degreeMap.set(top.to, (degreeMap.get(top.to) ?? 0) + 1);
    totalWeight += top.weight;

    frames.push(
      snapshot({
        activeNode: top.to,
        candidateEdge: top,
        line: 5,
        narration: `Masukkan (${labelOf(top.from)}, ${labelOf(top.to)}) dan simpul ${labelOf(top.to)} ke MST. Total bobot: ${formatWeight(totalWeight, weightMode)}.`,
      })
    );

    let pushed = 0;
    for (const item of adj.get(top.to) || []) {
      if (!takenNodes.has(item.neighbor)) {
        const weight =
          weightMode === "energy"
            ? computeCompositeWeight(item.edge, top.to, item.neighbor, nodeMap, degreeMap, isDynamicDistance, maxBaseWeight)
            : getEdgeBaseWeight(item.edge, nodeMap, isDynamicDistance);
        pq.push({
          edgeId: item.edge.id,
          from: top.to,
          to: item.neighbor,
          weight,
        });
        pushed += 1;
      }
    }

    if (pushed > 0 && takenNodes.size < nodes.length) {
      frames.push(
        snapshot({
          activeNode: top.to,
          line: 7,
          narration: `Tambahkan ${pushed} sisi tetangga dari ${labelOf(top.to)} yang belum masuk T ke PQ.`,
        })
      );
    }
  }

  const allReached = takenNodes.size === nodes.length;
  frames.push(
    snapshot({
      line: 8,
      narration: allReached
        ? `Selesai: ${takenNodes.size} simpul terhubung dengan total bobot MST ${formatWeight(totalWeight, weightMode)}.`
        : `Berhenti di ${takenNodes.size} dari ${nodes.length} simpul (graf belum terhubung seluruhnya).`,
    })
  );

  return frames;
}

