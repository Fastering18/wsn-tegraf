export function euclideanMeters(a, b) {
  return Math.hypot(a.xm - b.xm, a.ym - b.ym);
}

function connectComponents(nodes, edges) {
  const parent = new Map(nodes.map((n) => [n.id, n.id]));
  const find = (x) => {
    while (parent.get(x) !== x) {
      parent.set(x, parent.get(parent.get(x)));
      x = parent.get(x);
    }
    return x;
  };
  const unite = (a, b) => {
    const ra = find(a);
    const rb = find(b);
    if (ra !== rb) parent.set(ra, rb);
  };

  for (const e of edges) unite(e.u, e.v);

  const candidates = [];
  for (let i = 0; i < nodes.length; i += 1) {
    for (let j = i + 1; j < nodes.length; j += 1) {
      candidates.push({
        u: nodes[i].id,
        v: nodes[j].id,
        d: euclideanMeters(nodes[i], nodes[j]),
      });
    }
  }
  candidates.sort((a, b) => a.d - b.d);

  for (const c of candidates) {
    if (find(c.u) !== find(c.v)) {
      unite(c.u, c.v);
      edges.push({
        id: `${c.u}-${c.v}`,
        u: c.u,
        v: c.v,
        manualWeight: Number(c.d.toFixed(1)),
      });
    }
  }
}

